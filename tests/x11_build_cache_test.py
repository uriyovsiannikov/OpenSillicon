"""Exercise the X11 cache without compiling the vendored libraries."""
import pathlib
import re
import shutil
import subprocess
import tempfile
import unittest


class X11BuildCacheTest(unittest.TestCase):
    def test_cache_invalidation(self):
        repo = pathlib.Path(__file__).resolve().parents[1]
        with tempfile.TemporaryDirectory() as directory:
            root = pathlib.Path(directory)
            script = (repo / 'tools/build_x11_if_needed.sh').read_text()
            # Materialize every fingerprint input in an isolated source tree.
            for name in re.findall(r'"\$root/([^"$]+)"', script):
                path = root / name
                path.parent.mkdir(parents=True, exist_ok=True)
                if name.startswith(('user/', 'include/')) and not path.suffix:
                    path.mkdir(exist_ok=True)
                    (path / 'input.h').write_text('original')
                elif name == 'build/x11':
                    path.mkdir(exist_ok=True)
                elif not name.startswith('tools/'):
                    path.write_text('original')
                    path.chmod(0o755)
            (root / 'tools').mkdir(exist_ok=True)
            shutil.copy(repo / 'tools/build_x11_if_needed.sh', root / 'tools')
            (root / 'tools/build_feh.sh').write_text('# fixture\n')
            (root / 'tools/build_x11_apps.sh').write_text(
                '#!/bin/sh\nprintf "%s\\n" "$1" >> "$(dirname "$0")/calls"\n')
            stamp = root / 'build/x11/.apps-input.sha256'
            stamp.unlink(missing_ok=True)

            def run(expected):
                result = subprocess.run(['sh', str(root / 'tools/build_x11_if_needed.sh')],
                                        check=True, capture_output=True, text=True)
                self.assertIn(expected, result.stdout)

            run('full build')
            run('inputs unchanged')
            (root / 'build/libos/liblibos.a').write_text('new libc implementation')
            run('relink build')
            run('inputs unchanged')
            # Server-only changes must not rebuild client libraries.
            (root / 'user/xorg/tinyx').mkdir(exist_ok=True)
            (root / 'user/xorg/tinyx/server.c').write_text('changed server')
            run('inputs unchanged')
            # Python caches are generated by the toolchain, not source inputs.
            cache = root / 'user/xorg/deps/xcb-proto/__pycache__'
            cache.mkdir()
            (cache / 'module.pyc').write_bytes(b'bytecode')
            run('inputs unchanged')
            (root / 'user/libos/include/input.h').write_text('changed public API')
            run('full build')
            (root / 'build/x11/xterm/xterm').unlink()
            # The fake builder only records calls, so a missing binary stays missing.
            run('full build')
            self.assertEqual((root / 'tools/calls').read_text().splitlines(),
                             ['full', 'relink', 'full', 'full'])


if __name__ == '__main__':
    unittest.main()
