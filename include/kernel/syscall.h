#ifndef KERNEL_SYSCALL_H
#define KERNEL_SYSCALL_H

#include "kernel/fd.h"

#define SYSCALL_GET_ABI_VERSION 0U
#define SYSCALL_EXIT 1U
#define SYSCALL_WRITE 2U
#define SYSCALL_GETPID 3U
#define SYSCALL_FORK 4U
#define SYSCALL_EXEC 5U
#define SYSCALL_WAITPID 6U
#define SYSCALL_OPEN 7U
#define SYSCALL_CLOSE 8U
#define SYSCALL_READ 9U
#define SYSCALL_STAT 10U
#define SYSCALL_READDIR 11U
#define SYSCALL_EXEC_PATH 12U
#define SYSCALL_SLEEP_TICKS 13U
#define SYSCALL_PIPE 14U
#define SYSCALL_KILL 15U
#define SYSCALL_SIGACTION 16U
#define SYSCALL_SIGRETURN 17U
#define SYSCALL_SHM_CREATE 18U
#define SYSCALL_SHM_DETACH 19U
#define SYSCALL_SET_FS_BASE 20U
#define SYSCALL_MMAP 21U
#define SYSCALL_MUNMAP 22U
#define SYSCALL_MPROTECT 23U
#define SYSCALL_WRITEV 24U
#define SYSCALL_READV 25U
#define SYSCALL_IOCTL 26U
#define SYSCALL_EXEC_PATH_ARGV 27U
#define SYSCALL_PROCESS_SNAPSHOT 32U
#define SYSCALL_UDP_SOCKET 28U
#define SYSCALL_UDP_BIND 29U
#define SYSCALL_UDP_SENDTO 30U
#define SYSCALL_UDP_RECVFROM 31U
#define SYSCALL_ICMP_ECHO 33U
#define SYSCALL_CLOCK_GETTIME 34U
#define SYSCALL_NANOSLEEP 35U
#define SYSCALL_LSEEK 36U
#define SYSCALL_FSTAT 37U
#define SYSCALL_ABI_VERSION 1U

/* Keep every syscall assignment in both expressions. Summing the distinct
 * one-bit values equals their OR only when no number is assigned twice. */
#define SYSCALL_NUMBER_MASK (1ULL << SYSCALL_GET_ABI_VERSION | \
	1ULL << SYSCALL_EXIT | 1ULL << SYSCALL_WRITE | \
	1ULL << SYSCALL_GETPID | 1ULL << SYSCALL_FORK | \
	1ULL << SYSCALL_EXEC | 1ULL << SYSCALL_WAITPID | \
	1ULL << SYSCALL_OPEN | 1ULL << SYSCALL_CLOSE | \
	1ULL << SYSCALL_READ | 1ULL << SYSCALL_STAT | \
	1ULL << SYSCALL_READDIR | 1ULL << SYSCALL_EXEC_PATH | \
	1ULL << SYSCALL_SLEEP_TICKS | 1ULL << SYSCALL_PIPE | \
	1ULL << SYSCALL_KILL | 1ULL << SYSCALL_SIGACTION | \
	1ULL << SYSCALL_SIGRETURN | 1ULL << SYSCALL_SHM_CREATE | \
	1ULL << SYSCALL_SHM_DETACH | 1ULL << SYSCALL_SET_FS_BASE | \
	1ULL << SYSCALL_MMAP | 1ULL << SYSCALL_MUNMAP | \
	1ULL << SYSCALL_MPROTECT | 1ULL << SYSCALL_WRITEV | \
	1ULL << SYSCALL_READV | 1ULL << SYSCALL_IOCTL | \
	1ULL << SYSCALL_EXEC_PATH_ARGV | \
	1ULL << SYSCALL_UDP_SOCKET | 1ULL << SYSCALL_UDP_BIND | \
	1ULL << SYSCALL_UDP_SENDTO | 1ULL << SYSCALL_UDP_RECVFROM | \
	1ULL << SYSCALL_PROCESS_SNAPSHOT | 1ULL << SYSCALL_ICMP_ECHO | \
	1ULL << SYSCALL_CLOCK_GETTIME | 1ULL << SYSCALL_NANOSLEEP | \
	1ULL << SYSCALL_LSEEK | 1ULL << SYSCALL_FSTAT)
#define SYSCALL_NUMBER_BIT_SUM (1ULL << SYSCALL_GET_ABI_VERSION) + \
	(1ULL << SYSCALL_EXIT) + (1ULL << SYSCALL_WRITE) + \
	(1ULL << SYSCALL_GETPID) + (1ULL << SYSCALL_FORK) + \
	(1ULL << SYSCALL_EXEC) + (1ULL << SYSCALL_WAITPID) + \
	(1ULL << SYSCALL_OPEN) + (1ULL << SYSCALL_CLOSE) + \
	(1ULL << SYSCALL_READ) + (1ULL << SYSCALL_STAT) + \
	(1ULL << SYSCALL_READDIR) + (1ULL << SYSCALL_EXEC_PATH) + \
	(1ULL << SYSCALL_SLEEP_TICKS) + (1ULL << SYSCALL_PIPE) + \
	(1ULL << SYSCALL_KILL) + (1ULL << SYSCALL_SIGACTION) + \
	(1ULL << SYSCALL_SIGRETURN) + (1ULL << SYSCALL_SHM_CREATE) + \
	(1ULL << SYSCALL_SHM_DETACH) + (1ULL << SYSCALL_SET_FS_BASE) + \
	(1ULL << SYSCALL_MMAP) + (1ULL << SYSCALL_MUNMAP) + \
	(1ULL << SYSCALL_MPROTECT) + (1ULL << SYSCALL_WRITEV) + \
	(1ULL << SYSCALL_READV) + (1ULL << SYSCALL_IOCTL) + \
	(1ULL << SYSCALL_EXEC_PATH_ARGV) + \
	(1ULL << SYSCALL_UDP_SOCKET) + (1ULL << SYSCALL_UDP_BIND) + \
	(1ULL << SYSCALL_UDP_SENDTO) + (1ULL << SYSCALL_UDP_RECVFROM) + \
	(1ULL << SYSCALL_PROCESS_SNAPSHOT) + (1ULL << SYSCALL_ICMP_ECHO) + \
	(1ULL << SYSCALL_CLOCK_GETTIME) + (1ULL << SYSCALL_NANOSLEEP) + \
	(1ULL << SYSCALL_LSEEK) + (1ULL << SYSCALL_FSTAT)
_Static_assert(SYSCALL_PROCESS_SNAPSHOT < 64U,
	"extend syscall uniqueness guard before assigning numbers >= 64");
_Static_assert(SYSCALL_NUMBER_MASK == SYSCALL_NUMBER_BIT_SUM,
	"duplicate syscall number assignment");
#undef SYSCALL_NUMBER_MASK
#undef SYSCALL_NUMBER_BIT_SUM

void syscall_init(struct fd_table *table);

#endif
