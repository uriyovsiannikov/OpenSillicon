#ifndef KERNEL_SYSCALL_H
#define KERNEL_SYSCALL_H

#include "abi/syscall.h"
#include "kernel/fd.h"

/* Keep every syscall assignment in both expressions. Summing the distinct
 * one-bit values equals their OR only when no number is assigned twice. */
#define SYSCALL_NUMBER_MASK (1ULL << SYSCALL_GET_ABI_VERSION | \
	1ULL << SYSCALL_EXIT | 1ULL << SYSCALL_GETPID | \
	1ULL << SYSCALL_FORK | 1ULL << SYSCALL_EXEC | \
	1ULL << SYSCALL_WAITPID | 1ULL << SYSCALL_EXEC_PATH | \
	1ULL << SYSCALL_SLEEP_TICKS | 1ULL << SYSCALL_EXEC_PATH_ARGV | \
	1ULL << SYSCALL_PROCESS_SNAPSHOT | \
	1ULL << SYSCALL_WRITE | 1ULL << SYSCALL_OPEN | \
	1ULL << SYSCALL_CLOSE | 1ULL << SYSCALL_READ | \
	1ULL << SYSCALL_STAT | 1ULL << SYSCALL_READDIR | \
	1ULL << SYSCALL_WRITEV | 1ULL << SYSCALL_READV | \
	1ULL << SYSCALL_IOCTL | 1ULL << SYSCALL_LSEEK | \
	1ULL << SYSCALL_FSTAT | 1ULL << SYSCALL_GETDENTS | \
	1ULL << SYSCALL_FSTATAT | 1ULL << SYSCALL_PIPE | \
	1ULL << SYSCALL_KILL | 1ULL << SYSCALL_SIGACTION | \
	1ULL << SYSCALL_SIGRETURN | 1ULL << SYSCALL_SHM_CREATE | \
	1ULL << SYSCALL_SHM_DETACH | 1ULL << SYSCALL_SET_FS_BASE | \
	1ULL << SYSCALL_MMAP | 1ULL << SYSCALL_MUNMAP | \
	1ULL << SYSCALL_MPROTECT | 1ULL << SYSCALL_UDP_SOCKET | \
	1ULL << SYSCALL_UDP_BIND | 1ULL << SYSCALL_UDP_SENDTO | \
	1ULL << SYSCALL_UDP_RECVFROM | 1ULL << SYSCALL_ICMP_ECHO | \
	1ULL << SYSCALL_CLOCK_GETTIME | 1ULL << SYSCALL_NANOSLEEP | \
	1ULL << SYSCALL_FRAMEBUFFER_INFO | 1ULL << SYSCALL_FRAMEBUFFER_PRESENT | \
	1ULL << SYSCALL_KEYBOARD_POLL | 1ULL << SYSCALL_UNIX_SOCKET | \
	1ULL << SYSCALL_UNIX_BIND | 1ULL << SYSCALL_UNIX_LISTEN | \
	1ULL << SYSCALL_UNIX_CONNECT | 1ULL << SYSCALL_UNIX_ACCEPT | \
	1ULL << SYSCALL_SELECT | 1ULL << SYSCALL_UNIX_SHUTDOWN | \
	1ULL << SYSCALL_UNIX_GETSOCKOPT | 1ULL << SYSCALL_UNIX_SETSOCKOPT | \
	1ULL << SYSCALL_FCNTL | 1ULL << SYSCALL_DUP2 | \
	1ULL << SYSCALL_SIGPROCMASK | 1ULL << SYSCALL_MOUSE_POLL | \
	1ULL << SYSCALL_GETPPID | 1ULL << SYSCALL_PTY_PAIR)
#define SYSCALL_NUMBER_BIT_SUM (1ULL << SYSCALL_GET_ABI_VERSION) + \
	(1ULL << SYSCALL_EXIT) + (1ULL << SYSCALL_GETPID) + \
	(1ULL << SYSCALL_FORK) + (1ULL << SYSCALL_EXEC) + \
	(1ULL << SYSCALL_WAITPID) + (1ULL << SYSCALL_EXEC_PATH) + \
	(1ULL << SYSCALL_SLEEP_TICKS) + (1ULL << SYSCALL_EXEC_PATH_ARGV) + \
	(1ULL << SYSCALL_PROCESS_SNAPSHOT) + \
	(1ULL << SYSCALL_WRITE) + (1ULL << SYSCALL_OPEN) + \
	(1ULL << SYSCALL_CLOSE) + (1ULL << SYSCALL_READ) + \
	(1ULL << SYSCALL_STAT) + (1ULL << SYSCALL_READDIR) + \
	(1ULL << SYSCALL_WRITEV) + (1ULL << SYSCALL_READV) + \
	(1ULL << SYSCALL_IOCTL) + (1ULL << SYSCALL_LSEEK) + \
	(1ULL << SYSCALL_FSTAT) + (1ULL << SYSCALL_GETDENTS) + \
	(1ULL << SYSCALL_FSTATAT) + (1ULL << SYSCALL_PIPE) + \
	(1ULL << SYSCALL_KILL) + (1ULL << SYSCALL_SIGACTION) + \
	(1ULL << SYSCALL_SIGRETURN) + (1ULL << SYSCALL_SHM_CREATE) + \
	(1ULL << SYSCALL_SHM_DETACH) + (1ULL << SYSCALL_SET_FS_BASE) + \
	(1ULL << SYSCALL_MMAP) + (1ULL << SYSCALL_MUNMAP) + \
	(1ULL << SYSCALL_MPROTECT) + (1ULL << SYSCALL_UDP_SOCKET) + \
	(1ULL << SYSCALL_UDP_BIND) + (1ULL << SYSCALL_UDP_SENDTO) + \
	(1ULL << SYSCALL_UDP_RECVFROM) + (1ULL << SYSCALL_ICMP_ECHO) + \
	(1ULL << SYSCALL_CLOCK_GETTIME) + (1ULL << SYSCALL_NANOSLEEP) + \
	(1ULL << SYSCALL_FRAMEBUFFER_INFO) + \
	(1ULL << SYSCALL_FRAMEBUFFER_PRESENT) + \
	(1ULL << SYSCALL_KEYBOARD_POLL) + (1ULL << SYSCALL_UNIX_SOCKET) + \
	(1ULL << SYSCALL_UNIX_BIND) + (1ULL << SYSCALL_UNIX_LISTEN) + \
	(1ULL << SYSCALL_UNIX_CONNECT) + (1ULL << SYSCALL_UNIX_ACCEPT) + \
	(1ULL << SYSCALL_SELECT) + (1ULL << SYSCALL_UNIX_SHUTDOWN) + \
	(1ULL << SYSCALL_UNIX_GETSOCKOPT) + (1ULL << SYSCALL_UNIX_SETSOCKOPT) + \
	(1ULL << SYSCALL_FCNTL) + (1ULL << SYSCALL_DUP2) + \
	(1ULL << SYSCALL_SIGPROCMASK) + (1ULL << SYSCALL_MOUSE_POLL) + \
	(1ULL << SYSCALL_GETPPID) + (1ULL << SYSCALL_PTY_PAIR)
_Static_assert(SYSCALL_PTY_PAIR < 64U,
	"extend syscall uniqueness guard before assigning numbers >= 64");
_Static_assert(SYSCALL_NUMBER_MASK == SYSCALL_NUMBER_BIT_SUM,
	"duplicate syscall number assignment");
_Static_assert(SYSCALL_NUMBER_MASK ==
	((1ULL << (SYSCALL_PTY_PAIR + 1U)) - 1ULL),
	"syscall numbers must be dense from zero through the last assignment");
#undef SYSCALL_NUMBER_MASK
#undef SYSCALL_NUMBER_BIT_SUM

void syscall_init(struct fd_table *table);

#endif
